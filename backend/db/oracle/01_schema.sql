-- =====================================================================
-- Cube - schema for a NEW, EMPTY environment (Oracle 12c+). Run as the schema owner.
-- The existing CUBEDB already has these tables: use 00_upgrade_existing_cubedb.sql there instead.
-- Layout matches CUBEDB: identity primary keys, CU_ prefix, no foreign keys.
-- =====================================================================

CREATE TABLE CU_USER_MASTER (
    USER_ID        NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    USERNAME       VARCHAR2(100 CHAR) NOT NULL,
    EMAIL          VARCHAR2(150 CHAR) NOT NULL,
    PASSWORD_HASH  VARCHAR2(255 CHAR) NOT NULL,
    FIRST_NAME     VARCHAR2(100 CHAR),
    LAST_NAME      VARCHAR2(100 CHAR),
    STATUS         VARCHAR2(1 CHAR)   DEFAULT 'A',
    CREATED_AT     TIMESTAMP,
    UPDATED_AT     TIMESTAMP,
    REPORTING_MANAGER_ID NUMBER(19),
    EMPLOYEE_CODE  VARCHAR2(30 CHAR),
    DESIGNATION    VARCHAR2(100 CHAR),
    MUST_CHANGE_PASSWORD VARCHAR2(1 CHAR) DEFAULT 'N' NOT NULL,
    CONSTRAINT CU_USER_MASTER_PK PRIMARY KEY (USER_ID),
    CONSTRAINT CU_USER_MASTER_USERNAME_UK UNIQUE (USERNAME),
    CONSTRAINT CU_USER_MASTER_EMAIL_UK UNIQUE (EMAIL)
);

CREATE TABLE CU_GROUP_MASTER (
    GROUP_ID     NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    GROUP_CODE   VARCHAR2(50 CHAR)  NOT NULL,
    GROUP_NAME   VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION  VARCHAR2(255 CHAR),
    STATUS       VARCHAR2(1 CHAR)   DEFAULT 'A' NOT NULL,
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_GROUP_MASTER_PK PRIMARY KEY (GROUP_ID),
    CONSTRAINT CU_GROUP_MASTER_CODE_UK UNIQUE (GROUP_CODE)
);

-- One group per user.
CREATE TABLE CU_USER_GROUP (
    USER_ID     NUMBER(19)       NOT NULL,
    GROUP_ID    NUMBER(19)       NOT NULL,
    STATUS      VARCHAR2(1 CHAR) DEFAULT 'A' NOT NULL,
    CREATED_AT  TIMESTAMP        DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_USER_GROUP_PK PRIMARY KEY (USER_ID)
);

CREATE TABLE CU_MODULE_MASTER (
    MODULE_ID    NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    MODULE_CODE  VARCHAR2(50 CHAR)  NOT NULL,
    MODULE_NAME  VARCHAR2(100 CHAR),
    DESCRIPTION  VARCHAR2(255 CHAR),
    STATUS       VARCHAR2(1 CHAR)   DEFAULT 'A' NOT NULL,
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_MODULE_MASTER_PK PRIMARY KEY (MODULE_ID),
    CONSTRAINT CU_MODULE_MASTER_CODE_UK UNIQUE (MODULE_CODE)
);

-- Access codes belong to a module; permission = MODULE_CODE:ACCESS_CODE.
CREATE TABLE CU_ACCESS_MASTER (
    ACCESS_ID    NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    MODULE_ID    NUMBER(19)         NOT NULL,
    ACCESS_CODE  VARCHAR2(50 CHAR)  NOT NULL,
    DESCRIPTION  VARCHAR2(255 CHAR),
    STATUS       VARCHAR2(1 CHAR)   DEFAULT 'A' NOT NULL,
    CREATED_AT   TIMESTAMP          DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_ACCESS_MASTER_PK PRIMARY KEY (ACCESS_ID),
    CONSTRAINT CU_ACCESS_MASTER_UK UNIQUE (MODULE_ID, ACCESS_CODE)
);

CREATE TABLE CU_GROUP_ACCESS_TEMPLATE (
    GROUP_ID    NUMBER(19)       NOT NULL,
    ACCESS_ID   NUMBER(19)       NOT NULL,
    ALLOWED     VARCHAR2(1 CHAR) DEFAULT 'Y',
    STATUS      VARCHAR2(1 CHAR) DEFAULT 'A' NOT NULL,
    CREATED_AT  TIMESTAMP        DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_GROUP_ACCESS_TEMPLATE_PK PRIMARY KEY (ACCESS_ID, GROUP_ID)
);

CREATE TABLE CU_USER_ACCESS (
    USER_ID      NUMBER(19)       NOT NULL,
    ACCESS_ID    NUMBER(19)       NOT NULL,
    ALLOWED      VARCHAR2(1 CHAR) DEFAULT 'Y',
    EXPIRY_DATE  DATE,
    STATUS       VARCHAR2(1 CHAR) DEFAULT 'A' NOT NULL,
    CREATED_AT   TIMESTAMP        DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_USER_ACCESS_PK PRIMARY KEY (ACCESS_ID, USER_ID)
);

CREATE TABLE CU_REVOKED_TOKEN (
    TOKEN_ID    VARCHAR2(64)       NOT NULL,
    USERNAME    VARCHAR2(100 CHAR),
    EXPIRES_AT  TIMESTAMP          NOT NULL,
    REVOKED_AT  TIMESTAMP          NOT NULL,
    CONSTRAINT CU_REVOKED_TOKEN_PK PRIMARY KEY (TOKEN_ID)
);
CREATE INDEX CU_REVOKED_TOKEN_EXP_IX ON CU_REVOKED_TOKEN (EXPIRES_AT);

CREATE TABLE CU_KNOWLEDGE (
    KNOWLEDGE_ID      NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    TITLE             VARCHAR2(255 CHAR) NOT NULL,
    DESCRIPTION       CLOB,
    STATUS            VARCHAR2(20 CHAR),
    CREATED_BY        NUMBER(19)         NOT NULL,
    REJECTION_REASON  CLOB,
    REVIEWED_BY       NUMBER(19),
    REVIEWED_AT       TIMESTAMP,
    PUBLISHED_AT      TIMESTAMP,
    SEARCH_TEXT       CLOB,
    CREATED_AT        TIMESTAMP,
    UPDATED_AT        TIMESTAMP,
    ASSIGNED_REVIEWER_ID NUMBER(19),
    CONSTRAINT CU_KNOWLEDGE_PK PRIMARY KEY (KNOWLEDGE_ID)
);
CREATE INDEX CU_KNOWLEDGE_STATUS_IX ON CU_KNOWLEDGE (STATUS, PUBLISHED_AT);
CREATE INDEX CU_KNOWLEDGE_CREATOR_IX ON CU_KNOWLEDGE (CREATED_BY, UPDATED_AT);

CREATE TABLE CU_KEYWORD (
    KEYWORD_ID    NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    KEYWORD_NAME  VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT CU_KEYWORD_PK PRIMARY KEY (KEYWORD_ID),
    CONSTRAINT CU_KEYWORD_NAME_UK UNIQUE (KEYWORD_NAME)
);

CREATE TABLE CU_KNOWLEDGE_KEYWORD (
    KEYWORD_ID    NUMBER(19) NOT NULL,
    KNOWLEDGE_ID  NUMBER(19) NOT NULL,
    CONSTRAINT CU_KNOWLEDGE_KEYWORD_PK PRIMARY KEY (KEYWORD_ID, KNOWLEDGE_ID)
);
CREATE INDEX CU_KNOWLEDGE_KEYWORD_K_IX ON CU_KNOWLEDGE_KEYWORD (KNOWLEDGE_ID);

-- ONEDRIVE_FILE_ID holds the storage key (name kept from the original schema).
-- FILE_DATA is only used by attachments migrated from the previous version.
CREATE TABLE CU_ATTACHMENT (
    ATTACHMENT_ID     NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    KNOWLEDGE_ID      NUMBER(19)         NOT NULL,
    FILE_NAME         VARCHAR2(255 CHAR),
    CONTENT_TYPE      VARCHAR2(100 CHAR),
    FILE_SIZE         NUMBER(19),
    ONEDRIVE_FILE_ID  VARCHAR2(255 CHAR),
    FILE_DATA         BLOB,
    UPLOADED_BY       NUMBER(19),
    UPLOADED_AT       TIMESTAMP,
    CONSTRAINT CU_ATTACHMENT_PK PRIMARY KEY (ATTACHMENT_ID)
);
CREATE INDEX CU_ATTACHMENT_KNOWLEDGE_IDX ON CU_ATTACHMENT (KNOWLEDGE_ID);

CREATE TABLE CU_AUDIT_LOG (
    AUDIT_ID     NUMBER(19) GENERATED ALWAYS AS IDENTITY,
    ACTOR        VARCHAR2(100 CHAR),
    ACTION       VARCHAR2(50 CHAR)  NOT NULL,
    ENTITY_TYPE  VARCHAR2(50 CHAR),
    ENTITY_ID    VARCHAR2(100 CHAR),
    DETAILS      VARCHAR2(1000 CHAR),
    CREATED_AT   TIMESTAMP          NOT NULL,
    CONSTRAINT CU_AUDIT_LOG_PK PRIMARY KEY (AUDIT_ID)
);
CREATE INDEX CU_AUDIT_LOG_CREATED_IX ON CU_AUDIT_LOG (CREATED_AT);

CREATE TABLE CU_BOOKMARK (
    USER_ID       NUMBER(19) NOT NULL,
    KNOWLEDGE_ID  NUMBER(19) NOT NULL,
    CREATED_AT    TIMESTAMP  DEFAULT SYSTIMESTAMP,
    CONSTRAINT CU_BOOKMARK_PK PRIMARY KEY (USER_ID, KNOWLEDGE_ID)
);
CREATE INDEX CU_BOOKMARK_K_IX ON CU_BOOKMARK (KNOWLEDGE_ID);
CREATE INDEX CU_USER_MASTER_MANAGER_IX ON CU_USER_MASTER (REPORTING_MANAGER_ID);
CREATE INDEX CU_KNOWLEDGE_REVIEWER_IX ON CU_KNOWLEDGE (STATUS, ASSIGNED_REVIEWER_ID);
CREATE UNIQUE INDEX CU_USER_MASTER_EMPCODE_UX ON CU_USER_MASTER (UPPER(EMPLOYEE_CODE));
